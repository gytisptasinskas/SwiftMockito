import Foundation

public struct GeneratorConfiguration: Sendable {
    public var markedPaths: [String]
    public var inputs: [SourceInput]
    public var testModule: String
    public var outputDirectory: String
    public var expectedFiles: [String]

    public init(markedPaths: [String], inputs: [SourceInput], testModule: String,
                outputDirectory: String, expectedFiles: [String] = []) {
        self.markedPaths = markedPaths
        self.inputs = inputs
        self.testModule = testModule
        self.outputDirectory = outputDirectory
        self.expectedFiles = expectedFiles
    }
}

public struct GeneratorResult: Sendable {
    public let files: [String: String]
    public let diagnostics: [GeneratorDiagnostic]
    public var hasErrors: Bool { diagnostics.contains { $0.severity == .error } }
}

public enum Generator {
    public static func generate(_ configuration: GeneratorConfiguration) -> GeneratorResult {
        let index = SourceIndex(configuration.inputs, testModule: configuration.testModule)
        let resolver = ProtocolResolver(index: index)
        var files: [String: String] = [:]
        var diagnostics: [GeneratorDiagnostic] = []

        for marker in index.markers(in: Set(configuration.markedPaths)) {
            let fileName = "Mock\(marker.protocolName).swift"
            guard files[fileName] == nil else {
                diagnostics.append(.error("Mock\(marker.protocolName) is generated twice; remove the duplicate @GenerateMock(\(marker.protocolName).self)", at: marker))
                continue
            }
            if !configuration.expectedFiles.isEmpty, !configuration.expectedFiles.contains(fileName) {
                // The file is still written; the build fails on this error rather than on a missing output.
                diagnostics.append(.error("\(fileName) was not declared by the build plugin (the marker could not be read by the plugin's scanner); write each argument of @GenerateMock(...) as Name.self, with no comments inside the parentheses", at: marker))
            }
            switch resolver.resolve(marker, testModule: configuration.testModule) {
            case .success(let model):
                let synthesizer = DummySynthesizer(index: index, model: model, testModule: configuration.testModule)
                let mock = MockEmitter(model: model, synthesizer: synthesizer).emit()
                diagnostics += synthesizer.diagnostics
                let errors = synthesizer.diagnostics.filter { $0.severity == .error }
                files[fileName] = errors.isEmpty ? mock : failureFile(errors)
            case .failure(let failure):
                diagnostics += failure.diagnostics
                files[fileName] = failureFile(failure.diagnostics)
            }
        }
        for expected in configuration.expectedFiles where files[expected] == nil {
            let name = expected.dropFirst("Mock".count).dropLast(".swift".count)
            files[expected] = "// Generated by SwiftMockito. No active @GenerateMock(\(name).self) found.\n"
        }
        return GeneratorResult(files: files, diagnostics: diagnostics)
    }

    /// A comment-and-`#error` file that makes the build fail with the generator's messages.
    static func failureFile(_ diagnostics: [GeneratorDiagnostic]) -> String {
        var summary = ""
        for scalar in diagnostics.map(\.message).joined(separator: "; ").unicodeScalars {
            switch scalar {
            case "\r", "\n", "\t": summary += " "
            case "\\": summary += "\\\\"
            case "\"": summary += "\\\""
            default: summary.unicodeScalars.append(scalar)
            }
        }
        return "// Generated by SwiftMockito. Generation failed.\n#error(\"\(summary)\")\n"
    }

    /// CLI entry point. Exit codes: 0 success, 1 generation or write errors, 2 usage errors.
    /// Usage text and diagnostics go through `stderr`.
    public static func run(
        arguments: [String],
        stderr: (String) -> Void = { FileHandle.standardError.write(Data($0.utf8)) }
    ) -> Int32 {
        func usageError() -> Int32 {
            stderr(usage)
            return 2
        }
        guard arguments.first == "generate" else { return usageError() }
        var testModule: String?
        var output: String?
        var marked: [String] = []
        var sources: [(module: String, path: String)] = []
        var expected: [String] = []
        var remaining = arguments.dropFirst().makeIterator()
        while let flag = remaining.next() {
            guard let value = remaining.next() else { return usageError() }
            switch flag {
            case "--test-module": testModule = value
            case "--output": output = value
            case "--marked": marked.append(value)
            case "--expect": expected.append(value)
            case "--source-list":
                guard let list = try? String(contentsOfFile: value, encoding: .utf8) else {
                    stderr("error: cannot read \(value)\n")
                    return 2
                }
                for (number, line) in list.split(omittingEmptySubsequences: false, whereSeparator: \.isNewline).enumerated() where !line.isEmpty {
                    guard let eq = line.firstIndex(of: "=") else {
                        stderr("error: \(value):\(number + 1): expected Module=path\n")
                        return 2
                    }
                    sources.append((String(line[..<eq]), String(line[line.index(after: eq)...])))
                }
            case "--source", "--source-dir":
                guard let eq = value.firstIndex(of: "=") else { return usageError() }
                let module = String(value[..<eq])
                let path = String(value[value.index(after: eq)...])
                if flag == "--source" {
                    sources.append((module, path))
                } else {
                    guard let files = swiftFiles(in: path) else {
                        stderr("error: cannot read \(path)\n")
                        return 2
                    }
                    sources += files.map { (module, $0) }
                }
            default:
                return usageError()
            }
        }
        guard let testModule, let output else { return usageError() }

        func read(_ path: String) -> String? { try? String(contentsOfFile: path, encoding: .utf8) }
        var inputs: [SourceInput] = []
        for (path, module) in marked.map({ ($0, testModule) }) + sources.filter({ !marked.contains($0.path) }).map({ ($0.path, $0.module) }) {
            guard let text = read(path) else {
                stderr("error: cannot read \(path)\n")
                return 2
            }
            inputs.append(SourceInput(path: path, module: module, text: text))
        }

        let result = generate(GeneratorConfiguration(markedPaths: marked, inputs: inputs, testModule: testModule,
                                                     outputDirectory: output, expectedFiles: expected))
        for diagnostic in result.diagnostics { stderr(diagnostic.description + "\n") }

        do {
            try FileManager.default.createDirectory(atPath: output, withIntermediateDirectories: true)
        } catch {
            stderr("error: cannot write \(output): \(error.localizedDescription)\n")
            return 1
        }
        var writeFailed = false
        for (name, contents) in result.files.sorted(by: { $0.key < $1.key }) {
            let path = (output as NSString).appendingPathComponent(name)
            if read(path) != contents {   // keep mtimes stable for incremental builds
                do {
                    try contents.write(toFile: path, atomically: true, encoding: .utf8)
                } catch {
                    stderr("error: cannot write \(path): \(error.localizedDescription)\n")
                    writeFailed = true
                }
            }
        }
        return result.hasErrors || writeFailed ? 1 : 0
    }

    static let usage = """
        usage: SwiftMockitoGenerator generate --test-module <Module> --output <dir>
               --marked <file.swift>... [--source <Module>=<file.swift>...]
               [--source-dir <Module>=<dir>...] [--source-list <file>...]
               [--expect <MockName.swift>...]

        """

    /// Swift files under `directory`, or nil when it is not a readable directory. Files that
    /// SwiftMockito generated (by their first line) and hidden, `Pods` and build directories are skipped.
    private static func swiftFiles(in directory: String) -> [String]? {
        var isDirectory: ObjCBool = false
        guard FileManager.default.fileExists(atPath: directory, isDirectory: &isDirectory), isDirectory.boolValue,
              let enumerator = FileManager.default.enumerator(
                at: URL(filePath: directory), includingPropertiesForKeys: [.isDirectoryKey]) else { return nil }
        var result: [String] = []
        for case let url as URL in enumerator {
            let name = url.lastPathComponent
            if (try? url.resourceValues(forKeys: [.isDirectoryKey]))?.isDirectory == true {
                if name.hasPrefix(".") || name == "Pods" { enumerator.skipDescendants() }
                continue
            }
            guard name.hasSuffix(".swift") else { continue }
            let firstLine = (try? String(contentsOf: url, encoding: .utf8))?.prefix { $0 != "\n" } ?? ""
            guard !firstLine.hasPrefix("// Generated by SwiftMockito") else { continue }
            result.append(url.path)
        }
        return result.sorted()
    }
}
