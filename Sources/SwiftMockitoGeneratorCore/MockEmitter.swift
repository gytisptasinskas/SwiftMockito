import Foundation

struct MockEmitter {
    let model: MockModel
    let synthesizer: DummySynthesizer

    func emit() -> String {
        // Members first: emitting them tells the synthesizer which helpers are needed.
        var body = CodeWriter()
        for member in model.members {
            body.line()
            switch member {
            case .method(let m): emitMethod(m, &body)
            case .property(let p): emitProperty(p, &body)
            case .subscriptMember(let s): emitSubscript(s, &body)
            }
        }
        for helper in synthesizer.helpers {
            body.line()
            body.lines(helper)
        }

        var w = CodeWriter()
        w.line("// Generated by SwiftMockito from \(model.protocolName). Do not edit.")
        model.imports.forEach { w.line($0) }
        w.line()
        if let actor = model.globalActor { w.line("@\(actor)") }
        let generics = model.genericParameters.isEmpty ? "" : "<" + model.genericParameters.map { p in
            p.constraint.map { "\(p.name): \($0)" } ?? p.name
        }.joined(separator: ", ") + ">"
        w.block("\(model.access)final class \(model.mockName)\(generics): Mock, \(model.protocolName), @unchecked Sendable") { w in
            w.block("\(model.access)init(fileID: String = #fileID, filePath: StaticString = #filePath, line: UInt = #line, column: UInt = #column)") { w in
                w.line("super.init(name: \"\(model.mockName)\", site: CallSite(fileID: fileID, filePath: filePath, line: line, column: column))")
            }
            w.lines(String(body.output.dropLast()))
        }
        return w.output
    }

    // MARK: Members

    /// Associated types are the mock's generic parameters, so their dummies are unknown, like a generic method's.
    private var associatedNames: Set<String> { Set(model.genericParameters.map(\.name)) }

    private func emitMethod(_ m: Method, _ w: inout CodeWriter) {
        let key = keyList(genericTypes: m.genericParameters.map(\.name), parameters: m.parameters)
        w.block("\(model.access)\(nonsending(m.isAsync))func \(methodSignature(m))") { w in
            emitBody(identity: m.identity, key: key, args: argsList(m.parameters.map(\.name)),
                     isAsync: m.isAsync, isThrowing: m.isThrowing, returnType: m.returnType,
                     genericNames: Set(m.genericParameters.map(\.name)).union(associatedNames),
                     nonEscaping: m.parameters.filter(\.isNonEscapingClosure), &w)
        }
    }

    private func emitProperty(_ p: Property, _ w: inout CodeWriter) {
        let getterEffects = (p.getterAsync ? " async" : "") + (p.getterThrows ? " throws" : "")
        w.block("\(model.access)\(nonsending(p.getterAsync))var \(p.name): \(p.type)") { w in
            guard p.hasSetter || !getterEffects.isEmpty else {
                emitBody(identity: p.name, key: "[]", args: "", isAsync: false, isThrowing: false,
                         returnType: p.type, genericNames: associatedNames, &w)
                return
            }
            w.block("get\(getterEffects)") { w in
                emitBody(identity: p.name, key: "[]", args: "", isAsync: p.getterAsync, isThrowing: p.getterThrows,
                         returnType: p.type, genericNames: associatedNames, &w)
            }
            if p.hasSetter {
                w.block("set") { w in
                    emitBody(identity: "\(p.name)=", key: "[arg(newValue)]", args: ", args: newValue",
                             isAsync: false, isThrowing: false, returnType: nil, genericNames: associatedNames, &w)
                }
            }
        }
    }

    private func emitSubscript(_ s: Subscript, _ w: inout CodeWriter) {
        let params = s.parameters.map { declaration($0, subscriptStyle: true) }.joined(separator: ", ")
        let key = keyList(genericTypes: [], parameters: s.parameters)
        let names = s.parameters.map(\.name)
        let nonEscaping = s.parameters.filter(\.isNonEscapingClosure)
        w.block("\(model.access)subscript(\(params)) -> \(s.returnType)") { w in
            guard s.hasSetter else {
                emitBody(identity: s.identity, key: key, args: argsList(names), isAsync: false, isThrowing: false,
                         returnType: s.returnType, genericNames: associatedNames, nonEscaping: nonEscaping, &w)
                return
            }
            w.block("get") { w in
                emitBody(identity: s.identity, key: key, args: argsList(names), isAsync: false, isThrowing: false,
                         returnType: s.returnType, genericNames: associatedNames, nonEscaping: nonEscaping, &w)
            }
            w.block("set") { w in
                let setKey = key == "[]" ? "[arg(newValue)]" : String(key.dropLast()) + ", arg(newValue)]"
                emitBody(identity: "\(s.identity)=", key: setKey, args: argsList(names + ["newValue"]),
                         isAsync: false, isThrowing: false, returnType: nil, genericNames: associatedNames,
                         nonEscaping: nonEscaping, &w)
            }
        }
    }

    // MARK: Body

    /// `nonEscaping` lists the non-escaping closure parameters. The record and dispatch calls
    /// take escaping values, so each such call is wrapped in one `withoutActuallyEscaping` per parameter.
    private func emitBody(identity: String, key: String, args: String, isAsync: Bool, isThrowing: Bool,
                          returnType: String?, genericNames: Set<String>, nonEscaping: [Parameter] = [],
                          _ w: inout CodeWriter) {
        let effects: String = switch (isAsync, isThrowing) {
        case (true, true): ", effects: [.async, .throwing]"
        case (true, false): ", effects: .async"
        case (false, true): ", effects: .throwing"
        case (false, false): ""
        }
        let member = "\(model.mockName).\(identity)"
        // The recorded return type lets `thenReturn`/`thenAnswer` reject a closure of another type.
        let returns = returnType.map { ", returns: \(metatype($0))" } ?? ""
        w.block("if let capture = Capture.current") { w in
            withoutEscaping(nonEscaping, lead: "", prefix: "", &w) { w in
                w.line("capture.record(runtime, \"\(identity)\", key: \(key)\(args)\(effects)\(returns))")
            }
            if isThrowing {
                // Resolved D5: inside verifyInOrder, return a placeholder instead of throwing.
                if let returnType {
                    let fallback = genericNames.contains(returnType) ? nil
                        : synthesizer.fallback(for: returnType, member: member, genericNames: genericNames, warn: false)
                    w.line("if Capture.continuesAfterRecord, let placeholder = Dummies.placeholder(\(metatype(returnType))\(fallback.map { ", fallback: \($0)" } ?? "")) { return placeholder }")
                } else {
                    w.line("if Capture.continuesAfterRecord { return }")
                }
                w.line("throw CaptureSignal()")
            } else if let returnType {
                let fallback = synthesizer.fallback(for: returnType, member: member, genericNames: genericNames)
                    .map { ", fallback: \($0)" } ?? ""
                w.line("return Dummies.resolve(\(metatype(returnType)), for: \"\(member)\"\(fallback))")
            } else {
                w.line("return")
            }
        }
        let call = isThrowing ? "invokeThrowing" : "invoke"
        let prefix = (isThrowing ? "try " : "") + (isAsync ? "await " : "")
        let dispatch = "runtime.\(call)(\"\(identity)\", key: \(key)\(args))"
        guard !nonEscaping.isEmpty else {
            w.line("return \(prefix)\(dispatch)")
            return
        }
        guard isAsync else {
            withoutEscaping(nonEscaping, lead: "return \(prefix)", prefix: prefix, &w) { w in w.line("\(prefix)\(dispatch)") }
            return
        }
        // In a `nonisolated(nonsending)` member, an async `withoutActuallyEscaping` body is checked as
        // if it left the caller's isolation, so the closure cannot be sent. A local function with an
        // `isolated` parameter keeps the body on the caller's isolation.
        let params = (nonEscaping.map { "_ \($0.name): \(withoutAutoclosure($0.type))" } + ["_ isolation: isolated (any Actor)?"])
            .joined(separator: ", ")
        let signature = " async" + (isThrowing ? " throws" : "") + (returnType.map { " -> \($0)" } ?? "")
        w.block("func dispatch(\(params))\(signature)") { w in
            withoutEscaping(nonEscaping, lead: "return \(prefix)", prefix: prefix, &w) { w in
                w.line("_ = isolation")   // Load-bearing: isolates the closure to the parameter.
                w.line("return \(prefix)\(dispatch)")
            }
        }
        w.line("return \(prefix)dispatch(\((nonEscaping.map(\.name) + ["#isolation"]).joined(separator: ", ")))")
    }

    /// Nests `withoutActuallyEscaping(x) { x in … }` for each parameter, rebinding it to an escaping
    /// value under the same name. The outermost wrapper starts with `lead`; inner ones with `prefix`.
    private func withoutEscaping(_ parameters: [Parameter], lead: String, prefix: String, _ w: inout CodeWriter,
                                 _ body: (inout CodeWriter) -> Void) {
        guard let first = parameters.first else { return body(&w) }
        w.block("\(lead)withoutActuallyEscaping(\(first.name))", binding: first.name) { w in
            withoutEscaping(Array(parameters.dropFirst()), lead: prefix, prefix: prefix, &w, body)
        }
    }

    // MARK: Pieces

    /// Resolved D1: async members of a protocol without a global actor run on the caller's
    /// executor, so a `@MainActor` test's `when { … }` closure never hops before recording.
    private func nonsending(_ isAsync: Bool) -> String {
        isAsync && model.globalActor == nil ? "nonisolated(nonsending) " : ""
    }

    private func keyList(genericTypes: [String], parameters: [Parameter]) -> String {
        let types = genericTypes.map { "arg(type: \($0).self)" }
        let values = parameters.filter { !$0.isClosure }.map { p in
            p.isMetatype ? "arg(type: \(p.name))" : "arg(\(p.name))"
        }
        return "[" + (types + values).joined(separator: ", ") + "]"
    }

    /// A helper parameter cannot forward an `@autoclosure` argument, so it takes a plain closure.
    private func withoutAutoclosure(_ type: String) -> String {
        type.replacingOccurrences(of: "@autoclosure ", with: "")
    }

    private func argsList(_ names: [String]) -> String {
        names.isEmpty ? "" : ", args: " + names.joined(separator: ", ")
    }
}

/// `(any P).self` and `((Int) -> Void).self` need parentheses; `String!` is spelled `String?`;
/// other types take `.self` directly.
func metatype(_ type: String) -> String {
    if type.hasSuffix("!") { return "\(type.dropLast())?.self" }
    if type.hasPrefix("any ") || type.hasPrefix("some ") || hasTopLevelArrow(type) { return "(\(type)).self" }
    return "\(type).self"
}

/// Whether `->` occurs outside any brackets, i.e. the type itself is a function type.
private func hasTopLevelArrow(_ type: String) -> Bool {
    var depth = 0
    var previous: Character?
    for character in type {
        switch character {
        case "(", "[", "<": depth += 1
        case ")", "]": depth -= 1
        case ">": if previous == "-" { if depth == 0 { return true } } else { depth -= 1 }
        default: break
        }
        previous = character
    }
    return false
}

/// `name<T: C>(params) async throws -> R where …`: a method's signature as the mock and its
/// protocol dummies declare it.
func methodSignature(_ m: Method) -> String {
    let generics = m.genericParameters.isEmpty ? "" : "<" + m.genericParameters.map { p in
        p.constraint.map { "\(p.name): \($0)" } ?? p.name
    }.joined(separator: ", ") + ">"
    let params = m.parameters.map { declaration($0, subscriptStyle: false) }.joined(separator: ", ")
    let effects = (m.isAsync ? " async" : "") + (m.isThrowing ? " throws" : "")
    let returns = m.returnType.map { " -> \($0)" } ?? ""
    let whereClause = m.genericWhereClause.map { " \($0)" } ?? ""
    return "\(m.name)\(generics)(\(params))\(effects)\(returns)\(whereClause)"
}

/// Methods: `_ name: T` / `label name: T` / `name: T`. Subscripts: `name: T` means no label.
func declaration(_ p: Parameter, subscriptStyle: Bool) -> String {
    let type = p.isVariadic ? "\(p.type)..." : p.type
    switch p.label {
    case nil: return subscriptStyle ? "\(p.name): \(type)" : "_ \(p.name): \(type)"
    case p.name?: return subscriptStyle ? "\(p.name) \(p.name): \(type)" : "\(p.name): \(type)"
    case let label?: return "\(label) \(p.name): \(type)"
    }
}
