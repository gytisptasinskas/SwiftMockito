struct MockEmitter {
    let model: MockModel
    let synthesizer: DummySynthesizer

    func emit() -> String {
        // Members first: emitting them tells the synthesizer which helpers are needed.
        var body = CodeWriter()
        for member in model.members {
            body.line()
            switch member {
            case .method(let m): emitMethod(m, &body)
            case .property(let p): emitProperty(p, &body)
            case .subscriptMember(let s): emitSubscript(s, &body)
            }
        }
        for helper in synthesizer.helpers {
            body.line()
            body.lines(helper)
        }

        var w = CodeWriter()
        w.line("// Generated by SwiftMockito from \(model.protocolName). Do not edit.")
        model.imports.forEach { w.line($0) }
        w.line()
        if let actor = model.globalActor { w.line("@\(actor)") }
        w.block("\(model.access)final class \(model.mockName): Mock, \(model.protocolName), @unchecked Sendable") { w in
            w.block("\(model.access)init(fileID: String = #fileID, filePath: StaticString = #filePath, line: UInt = #line, column: UInt = #column)") { w in
                w.line("super.init(name: \"\(model.mockName)\", site: CallSite(fileID: fileID, filePath: filePath, line: line, column: column))")
            }
            w.lines(String(body.output.dropLast()))
        }
        return w.output
    }

    // MARK: Members

    private func emitMethod(_ m: Method, _ w: inout CodeWriter) {
        let generics = m.genericParameters.isEmpty ? "" : "<" + m.genericParameters.map { p in
            p.constraint.map { "\(p.name): \($0)" } ?? p.name
        }.joined(separator: ", ") + ">"
        let params = m.parameters.map { declaration($0, subscriptStyle: false) }.joined(separator: ", ")
        let effects = (m.isAsync ? " async" : "") + (m.isThrowing ? " throws" : "")
        let returns = m.returnType.map { " -> \($0)" } ?? ""
        let whereClause = m.genericWhereClause.map { " \($0)" } ?? ""
        let key = keyList(genericTypes: m.genericParameters.map(\.name), parameters: m.parameters)
        w.block("\(model.access)\(nonsending(m.isAsync))func \(m.name)\(generics)(\(params))\(effects)\(returns)\(whereClause)") { w in
            emitBody(identity: m.identity, key: key, args: argsList(m.parameters.map(\.name)),
                     isAsync: m.isAsync, isThrowing: m.isThrowing, returnType: m.returnType,
                     genericNames: Set(m.genericParameters.map(\.name)), &w)
        }
    }

    private func emitProperty(_ p: Property, _ w: inout CodeWriter) {
        let getterEffects = (p.getterAsync ? " async" : "") + (p.getterThrows ? " throws" : "")
        w.block("\(model.access)\(nonsending(p.getterAsync))var \(p.name): \(p.type)") { w in
            guard p.hasSetter || !getterEffects.isEmpty else {
                emitBody(identity: p.name, key: "[]", args: "", isAsync: false, isThrowing: false,
                         returnType: p.type, genericNames: [], &w)
                return
            }
            w.block("get\(getterEffects)") { w in
                emitBody(identity: p.name, key: "[]", args: "", isAsync: p.getterAsync, isThrowing: p.getterThrows,
                         returnType: p.type, genericNames: [], &w)
            }
            if p.hasSetter {
                w.block("set") { w in
                    emitBody(identity: "\(p.name)=", key: "[arg(newValue)]", args: ", args: newValue",
                             isAsync: false, isThrowing: false, returnType: nil, genericNames: [], &w)
                }
            }
        }
    }

    private func emitSubscript(_ s: Subscript, _ w: inout CodeWriter) {
        let params = s.parameters.map { declaration($0, subscriptStyle: true) }.joined(separator: ", ")
        let key = keyList(genericTypes: [], parameters: s.parameters)
        let names = s.parameters.map(\.name)
        w.block("\(model.access)subscript(\(params)) -> \(s.returnType)") { w in
            guard s.hasSetter else {
                emitBody(identity: s.identity, key: key, args: argsList(names), isAsync: false, isThrowing: false,
                         returnType: s.returnType, genericNames: [], &w)
                return
            }
            w.block("get") { w in
                emitBody(identity: s.identity, key: key, args: argsList(names), isAsync: false, isThrowing: false,
                         returnType: s.returnType, genericNames: [], &w)
            }
            w.block("set") { w in
                let setKey = key == "[]" ? "[arg(newValue)]" : String(key.dropLast()) + ", arg(newValue)]"
                emitBody(identity: "\(s.identity)=", key: setKey, args: argsList(names + ["newValue"]),
                         isAsync: false, isThrowing: false, returnType: nil, genericNames: [], &w)
            }
        }
    }

    // MARK: Body

    private func emitBody(identity: String, key: String, args: String, isAsync: Bool, isThrowing: Bool,
                          returnType: String?, genericNames: Set<String>, _ w: inout CodeWriter) {
        let effects: String = switch (isAsync, isThrowing) {
        case (true, true): ", effects: [.async, .throwing]"
        case (true, false): ", effects: .async"
        case (false, true): ", effects: .throwing"
        case (false, false): ""
        }
        let member = "\(model.mockName).\(identity)"
        w.block("if let capture = Capture.current") { w in
            w.line("capture.record(runtime, \"\(identity)\", key: \(key)\(args)\(effects))")
            if isThrowing {
                // Resolved D5: inside verifyInOrder, return a placeholder instead of throwing.
                if let returnType {
                    let fallback = genericNames.contains(returnType) ? nil
                        : synthesizer.fallback(for: returnType, member: member, genericNames: genericNames, warn: false)
                    w.line("if Capture.continuesAfterRecord, let placeholder = Dummies.placeholder(\(metatype(returnType))\(fallback.map { ", fallback: \($0)" } ?? "")) { return placeholder }")
                } else {
                    w.line("if Capture.continuesAfterRecord { return }")
                }
                w.line("throw CaptureSignal()")
            } else if let returnType {
                let fallback = synthesizer.fallback(for: returnType, member: member, genericNames: genericNames)
                    .map { ", fallback: \($0)" } ?? ""
                w.line("return Dummies.resolve(\(metatype(returnType)), for: \"\(member)\"\(fallback))")
            } else {
                w.line("return")
            }
        }
        let call = isThrowing ? "invokeThrowing" : "invoke"
        let prefix = (isThrowing ? "try " : "") + (isAsync ? "await " : "")
        w.line("return \(prefix)runtime.\(call)(\"\(identity)\", key: \(key)\(args))")
    }

    // MARK: Pieces

    /// Resolved D1: async members of a protocol without a global actor run on the caller's
    /// executor, so a `@MainActor` test's `when { … }` closure never hops before recording.
    private func nonsending(_ isAsync: Bool) -> String {
        isAsync && model.globalActor == nil ? "nonisolated(nonsending) " : ""
    }

    /// Methods: `_ name: T` / `label name: T` / `name: T`. Subscripts: `name: T` means no label.
    private func declaration(_ p: Parameter, subscriptStyle: Bool) -> String {
        switch p.label {
        case nil: return subscriptStyle ? "\(p.name): \(p.type)" : "_ \(p.name): \(p.type)"
        case p.name?: return subscriptStyle ? "\(p.name) \(p.name): \(p.type)" : "\(p.name): \(p.type)"
        case let label?: return "\(label) \(p.name): \(p.type)"
        }
    }

    private func keyList(genericTypes: [String], parameters: [Parameter]) -> String {
        let types = genericTypes.map { "arg(type: \($0).self)" }
        let values = parameters.filter { !$0.isClosure }.map { p in
            p.isMetatype ? "arg(type: \(p.name))" : "arg(\(p.name))"
        }
        return "[" + (types + values).joined(separator: ", ") + "]"
    }

    private func argsList(_ names: [String]) -> String {
        names.isEmpty ? "" : ", args: " + names.joined(separator: ", ")
    }
}

/// `(any P).self` and `(A, B).self` need parentheses; other types take `.self` directly.
func metatype(_ type: String) -> String {
    if type.hasPrefix("any ") || type.hasPrefix("some ") { return "(\(type)).self" }
    return "\(type).self"
}
